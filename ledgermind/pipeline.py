"""The import pipeline: inbox → importers → dedupe → categorize → write → validate."""

from __future__ import annotations

import hashlib
from collections import Counter
from dataclasses import dataclass, field
from datetime import datetime
from decimal import Decimal
from pathlib import Path

from . import ledger
from .categorizers import HistoryCategorizer, LLMCategorizer, RulesCategorizer, categorize
from .config import Config, load_config
from .importers import get_importer
from .models import Transaction
from .writer import render


@dataclass
class Summary:
    files: int = 0
    new: int = 0
    duplicates: int = 0
    needs_review: int = 0
    output: Path | None = None
    rejected: bool = False
    errors: list[str] = field(default_factory=list)
    in_transit: Decimal = Decimal(0)


def make_import_id(txn: Transaction, occurrence: int) -> str:
    """Stable ID so re-importing the same statement never duplicates entries.

    `occurrence` separates genuinely identical lines in one file
    (two $5.00 coffees on the same day).
    """
    key = f"{txn.account}|{txn.date}|{txn.amount}|{txn.description}|{occurrence}"
    return hashlib.sha1(key.encode()).hexdigest()[:16]


def build_categorizers(cfg: Config, entries, accounts: set[str]) -> list:
    cats: list = []
    if cfg.rules and cfg.rules.exists():
        cats.append(RulesCategorizer.from_file(cfg.rules))
    cats.append(HistoryCategorizer(entries))
    if cfg.llm.get("enabled"):
        choices = [a for a in accounts if a.startswith(("Expenses:", "Income:", "Assets:Transfers"))]
        cats.append(
            LLMCategorizer(
                provider=cfg.llm.get("provider", "ollama"),
                model=cfg.llm.get("model", "llama3.1"),
                accounts=choices,
                base_url=cfg.llm.get("base_url"),
            )
        )
    return cats


def run_import(config_path: str | Path, dry_run: bool = False) -> Summary:
    cfg = load_config(config_path)
    summary = Summary()

    entries, errors_before, _ = ledger.load(cfg.ledger)
    existing = ledger.import_ids(entries)
    accounts = ledger.open_accounts(entries)
    categorizers = build_categorizers(cfg, entries, accounts)

    new: list[Transaction] = []
    for source in cfg.sources:
        importer = get_importer(source.importer)
        for path in sorted(cfg.inbox.glob(source.pattern)):
            summary.files += 1
            seen: Counter[str] = Counter()
            for txn in importer.extract(path, source.account, source.options):
                key = f"{txn.account}|{txn.date}|{txn.amount}|{txn.description}"
                seen[key] += 1
                txn.import_id = make_import_id(txn, seen[key])
                if txn.import_id in existing:
                    summary.duplicates += 1
                    continue
                categorize(txn, categorizers, accounts)
                new.append(txn)

    new.sort(key=lambda t: (t.date, t.account))
    summary.new = len(new)
    summary.needs_review = sum(t.needs_review(cfg.review_threshold) for t in new)

    if new and not dry_run:
        cfg.imports_dir.mkdir(parents=True, exist_ok=True)
        placeholder = cfg.imports_dir / "00-placeholder.beancount"
        if not placeholder.exists():  # keeps an include glob valid if import files are removed
            placeholder.write_text(';; Placeholder so `include "imports/*.beancount"` always matches.\n')
        out = cfg.imports_dir / f"import-{datetime.now():%Y%m%d-%H%M%S}.beancount"
        body = "\n".join(render(t, cfg.review_threshold) for t in new)
        out.write_text(
            f";; Generated by ledgermind on {datetime.now():%Y-%m-%d %H:%M}.\n"
            ";; Entries flagged '!' need review: fix the account, then change '!' to '*'.\n\n" + body,
            encoding="utf-8",
        )
        summary.output = out

        # Validate the whole ledger. If our file introduced errors, quarantine it.
        entries_after, errors_after, _ = ledger.load(cfg.ledger)
        if len(errors_after) > len(errors_before):
            rejected = out.with_suffix(".rejected")
            out.rename(rejected)
            summary.output = rejected
            summary.rejected = True
            summary.errors = [ledger.format_error(e) for e in errors_after]
        else:
            entries = entries_after

    summary.in_transit = ledger.in_transit_balance(entries)
    return summary
